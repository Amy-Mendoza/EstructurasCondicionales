calif = float(input("Ingrese la calificación: "))
if calif >= 90:
    print("La calificación es A")
elif calif >= 80:
    print("La calificación es B")
elif calif >= 70:
    print("La calificación es C")
elif calif >= 60:
    print("La calificación es D")
else:
    print("La calificación es F")